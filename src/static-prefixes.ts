// Paths that never render a view and never read the session. The per-request
// hook in app.ts skips auth resolution and view-context building for them,
// so a page load's dozens of asset requests cost zero JWT verifications and
// zero user queries. Keep in step with public/ (src/static-assets.ts) and the
// image routes in src/web/files/routes.ts.
const STATIC_PREFIXES = [
  // The client libraries, copied from node_modules by `npm run generate:modules`.
  '/modules/',
  '/assets/',
  '/js/',
  // Built from npm packages by `npm run generate:vendor` (public/vendor/).
  '/vendor/',
  '/file/',
] as const;

const STATIC_FILES = [
  '/bundle.css',
  '/sw.js',
  '/manifest.json',
  // The health endpoints (src/web/health): the connectivity heartbeat
  // (views/assets/page/connectivity.ts, /health/live) and the container healthcheck
  // must never cost a JWT verification or a user query, nor a log line.
  // /healthz is /health/ready's alias for stale clients.
  '/health/live',
  '/health/ready',
  '/healthz',
  // The metrics scrape (src/web/metrics), every 15 s: no session, no
  // request log line.
  '/metrics',
  '/favicon.ico',
  '/robots.txt',
  // Generated by `npm run generate:notices`; linked from /about.
  '/THIRD-PARTY-NOTICES.txt',
  '/llms.txt',
  '/llms-full.txt',
] as const;

// Every /file/** route is an image served by src/web/files/routes.ts without
// a session; a new page under that prefix would need its own carve-out here.
export function isStaticPath(url: string): boolean {
  const path = url.split('?')[0];
  return (
    (STATIC_FILES as readonly string[]).includes(path) ||
    STATIC_PREFIXES.some((prefix) => path.startsWith(prefix))
  );
}
