/**
 * `make lg-check`: a shrink-only count of page-level desktop-width classes (#1066).
 *
 * Exact by construction, not by pattern: Tailwind's own scanner (`@tailwindcss/oxide`) extracts
 * the class candidates of every .ts/.tsx file under `src` (spec files and the paths
 * scripts/ci/lg_count.conf exempts aside), each candidate is compiled against views/assets/main.css
 * (its custom variants and breakpoints included), and it counts when the emitted CSS has an
 * `@media` that can hold at a width of 64rem (1024px) or more. `not-max-lg:`, `*:lg:`,
 * `[@media(min-width:64rem)]:` count; `node:crypto`, `@lg:` (a container query) and `max-lg:` do
 * not. Each occurrence counts. A file fails when its count is above its `known` line or it has
 * none; below its line it passes but says to lower the number in the same PR.
 *
 * `--staged` (the pre-commit hook, `make lg-check-staged`) reads the conf and every file from the
 * index in one `git cat-file --batch`, so it judges what is about to be committed.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, readdirSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { compile } from '@tailwindcss/node';
import { Scanner } from '@tailwindcss/oxide';

const ROOT = resolve(__dirname, '..');
const CONF = 'scripts/ci/lg_count.conf';
const MAIN_CSS = join(ROOT, 'views/assets/main.css');
const LG_PX = 64 * 16;
const REM_PX = 16;
// Generated by `npm run generate:fonts`, absent on a fresh checkout, and holds no variants.
const FONTS_IMPORT =
  /^@import "\.\.\/\.\.\/public\/vendor\/fonts\/fonts\.css";\n/m;

// Three-valued truth: a media condition the guard cannot evaluate is `unknown`, which counts.
type Truth = 'yes' | 'no' | 'unknown';
type Node = {
  eval: (width: number) => Truth;
  thresholds: number[];
  mentionsWidth: boolean;
};

const LENGTH = /^(\d*\.?\d+)(px|rem|em)$/;

function px(value: string): number | undefined {
  const m = LENGTH.exec(value.trim());
  if (!m) return undefined;
  return parseFloat(m[1]) * (m[2] === 'px' ? 1 : REM_PX);
}

function and(a: Truth, b: Truth): Truth {
  if (a === 'no' || b === 'no') return 'no';
  return a === 'yes' && b === 'yes' ? 'yes' : 'unknown';
}
function or(a: Truth, b: Truth): Truth {
  if (a === 'yes' || b === 'yes') return 'yes';
  return a === 'no' && b === 'no' ? 'no' : 'unknown';
}
function not(a: Truth): Truth {
  if (a === 'unknown') return a;
  return a === 'yes' ? 'no' : 'yes';
}

const COMPARE: Record<string, (a: number, b: number) => boolean> = {
  '>=': (a, b) => a >= b,
  '<=': (a, b) => a <= b,
  '>': (a, b) => a > b,
  '<': (a, b) => a < b,
  '=': (a, b) => a === b,
};
const FLIP: Record<string, string> = {
  '>=': '<=',
  '<=': '>=',
  '>': '<',
  '<': '>',
  '=': '=',
};

/** One `(feature)`: a width comparison it can evaluate, or an opaque leaf. */
function feature(text: string): Node {
  const t = text.trim();
  const mentionsWidth = /width/.test(t);
  const opaque: Node = { eval: () => 'unknown', thresholds: [], mentionsWidth };
  const leaf = (test: (w: number) => boolean, limits: number[]): Node => ({
    eval: (w) => (test(w) ? 'yes' : 'no'),
    thresholds: limits,
    mentionsWidth: true,
  });
  const minMax = /^(min|max)-width\s*:\s*(.+)$/.exec(t);
  if (minMax) {
    const n = px(minMax[2]);
    if (n === undefined) return opaque;
    return leaf((w) => (minMax[1] === 'min' ? w >= n : w <= n), [n]);
  }
  const widthFirst = /^width\s*(>=|<=|>|<|=)\s*(.+)$/.exec(t);
  if (widthFirst) {
    const n = px(widthFirst[2]);
    if (n === undefined) return opaque;
    return leaf((w) => COMPARE[widthFirst[1]](w, n), [n]);
  }
  const widthLast = /^(.+?)\s*(>=|<=|>|<|=)\s*width$/.exec(t);
  if (widthLast) {
    const n = px(widthLast[1]);
    if (n === undefined) return opaque;
    return leaf((w) => COMPARE[FLIP[widthLast[2]]](w, n), [n]);
  }
  const range = /^(.+?)\s*(<=|<|>=|>)\s*width\s*(<=|<|>=|>)\s*(.+)$/.exec(t);
  if (range) {
    const [lo, hi] = [px(range[1]), px(range[4])];
    if (lo === undefined || hi === undefined) return opaque;
    return leaf(
      (w) => COMPARE[FLIP[range[2]]](w, lo) && COMPARE[range[3]](w, hi),
      [lo, hi],
    );
  }
  return opaque;
}

/** Splits `text` into top-level words and parenthesised groups. */
function tokens(text: string): string[] {
  const out: string[] = [];
  let depth = 0;
  let current = '';
  for (const ch of text) {
    if (ch === '(') depth++;
    if (depth === 0 && /\s/.test(ch)) {
      if (current) out.push(current);
      current = '';
      continue;
    }
    current += ch;
    if (ch === ')') depth--;
  }
  if (current) out.push(current);
  return out;
}

function parseCondition(text: string): Node {
  const parts = tokens(text);
  // A leading `not` negates the whole rest (`not all and (...)`): it binds loosest.
  if (parts[0] === 'not') {
    const inner = parseCondition(parts.slice(1).join(' '));
    return { ...inner, eval: (w) => not(inner.eval(w)) };
  }
  const combine = (
    op: 'and' | 'or',
    fold: (a: Truth, b: Truth) => Truth,
  ): Node | undefined => {
    const at = parts.indexOf(op);
    if (at < 0) return undefined;
    const left = parseCondition(parts.slice(0, at).join(' '));
    const right = parseCondition(parts.slice(at + 1).join(' '));
    return {
      eval: (w) => fold(left.eval(w), right.eval(w)),
      thresholds: [...left.thresholds, ...right.thresholds],
      mentionsWidth: left.mentionsWidth || right.mentionsWidth,
    };
  };
  const combined = combine('or', or) ?? combine('and', and);
  if (combined) return combined;
  if (
    parts.length === 1 &&
    parts[0].startsWith('(') &&
    parts[0].endsWith(')')
  ) {
    const inner = parts[0].slice(1, -1).trim();
    return /^\s*(\(|not\b)/.test(inner) || /\b(and|or)\b/.test(inner)
      ? parseCondition(inner)
      : feature(inner);
  }
  // A media type (`screen`, `all`, `print`) or anything else: opaque, no width in it.
  return { eval: () => 'unknown', thresholds: [], mentionsWidth: false };
}

/**
 * Whether an `@media` prelude is a desktop-only width condition: it can hold at 64rem or more and
 * does not already hold just below it. `sm:`/`md:` (on from 40rem/48rem) and `max-lg:` are not;
 * `lg:`, `not-max-lg:` and an opaque `min-[calc(...)]` are.
 */
export function appliesAtDesktop(prelude: string): boolean {
  return prelude
    .toLowerCase()
    .split(',')
    .some((query) => {
      const node = parseCondition(query.replace(/^\s*only\s+/, ''));
      if (!node.mentionsWidth) return false;
      const samples = [
        LG_PX,
        1e7,
        ...node.thresholds.flatMap((t) => [t, t + 0.01, t - 0.01]),
      ].filter((w) => w >= LG_PX);
      return (
        node.eval(LG_PX - 0.01) !== 'yes' &&
        samples.some((w) => node.eval(w) !== 'no')
      );
    });
}

/** The `@media` preludes of a compiled stylesheet (container queries are `@container`, never here). */
export function mediaPreludes(css: string): string[] {
  return [...css.matchAll(/@media\s+([^{;]+)\{/g)].map((m) => m[1].trim());
}

function tally(css: string): Map<string, number> {
  const counts = new Map<string, number>();
  for (const prelude of mediaPreludes(css))
    counts.set(prelude, (counts.get(prelude) ?? 0) + 1);
  return counts;
}

/** Whether `after` has a desktop-width `@media` that `before` lacks (one more of a prelude counts). */
export function addsDesktopMedia(
  after: Map<string, number>,
  before: Map<string, number>,
): boolean {
  for (const [prelude, n] of after) {
    if (n > (before.get(prelude) ?? 0) && appliesAtDesktop(prelude))
      return true;
  }
  return false;
}

export interface Conf {
  src: string;
  exempt: string[];
  known: Map<string, number>;
}

export function readConf(text: string): Conf {
  const conf: Conf = { src: 'src/web', exempt: [], known: new Map() };
  text.split('\n').forEach((raw, i) => {
    const line = raw.split('#', 1)[0].trim().split(/\s+/).filter(Boolean);
    if (line.length === 0) return;
    if (line[0] === 'src' && line.length === 2) conf.src = line[1];
    else if (line[0] === 'exempt' && line.length === 2)
      conf.exempt.push(line[1]);
    else if (line[0] === 'known' && line.length === 3 && /^\d+$/.test(line[2]))
      conf.known.set(line[1], Number(line[2]));
    else
      throw new Error(
        `${CONF}:${i + 1}: expected src|exempt <path> or known <path> <count>`,
      );
  });
  return conf;
}

export function isCounted(rel: string, exempt: string[]): boolean {
  const name = rel.slice(rel.lastIndexOf('/') + 1);
  const exempted = exempt.some(
    (e) => rel === e || (e.endsWith('/') && rel.startsWith(e)),
  );
  return /\.tsx?$/.test(rel) && !name.includes('.spec.') && !exempted;
}

/**
 * Compiles candidates one at a time against the app's stylesheet and says which add a desktop-width
 * `@media`; memoised for the run. Tailwind's `build()` is cumulative (it remembers every candidate
 * it has seen), so a candidate is judged by what it adds to the previous build's media queries;
 * main.css's own hand-written ones are in the baseline and never the candidate's.
 */
export async function desktopClassifier(): Promise<
  (candidate: string) => boolean
> {
  const css = readFileSync(MAIN_CSS, 'utf8').replace(FONTS_IMPORT, '');
  // daisyUI prints its version banner to stdout when the plugin loads.
  const log = console.log;
  console.log = () => undefined;
  const compiler = await compile(css, {
    base: dirname(MAIN_CSS),
    onDependency: () => undefined,
  }).finally(() => {
    console.log = log;
  });
  let previous = tally(compiler.build([]));
  const cache = new Map<string, boolean>();
  return (candidate) => {
    let hit = cache.get(candidate);
    if (hit === undefined) {
      // Every variant has a colon; a class without one has no media query to find.
      if (candidate.includes(':')) {
        const next = tally(compiler.build([candidate]));
        hit = addsDesktopMedia(next, previous);
        previous = next;
      } else {
        hit = false;
      }
      cache.set(candidate, hit);
    }
    return hit;
  };
}

export function countFile(
  scanner: Scanner,
  isDesktop: (candidate: string) => boolean,
  rel: string,
  content: string,
): number {
  const extension = rel.slice(rel.lastIndexOf('.') + 1);
  return scanner
    .getCandidatesWithPositions({ content, extension })
    .filter((c) => isDesktop(c.candidate)).length;
}

function walk(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory()
      ? walk(join(dir, e.name))
      : [relative(ROOT, join(dir, e.name)).split('\\').join('/')],
  );
}

/** Every path's staged blob through one `git cat-file --batch`, not a process per file. */
export function readIndex(
  paths: string[],
  options: { cwd?: string; env?: NodeJS.ProcessEnv } = {},
): Map<string, string> {
  const out = execFileSync('git', ['cat-file', '--batch'], {
    cwd: options.cwd ?? ROOT,
    env: options.env,
    input: paths.map((p) => `:${p}\n`).join(''),
    maxBuffer: 1 << 30,
  });
  const blobs = new Map<string, string>();
  let pos = 0;
  for (const path of paths) {
    const end = out.indexOf('\n', pos);
    const header = out.subarray(pos, end).toString().split(' ');
    if (header.length !== 3 || header[1] !== 'blob')
      throw new Error(`lg-check: ${path} is not in the index`);
    const size = Number(header[2]);
    blobs.set(path, out.subarray(end + 1, end + 1 + size).toString('utf8'));
    pos = end + 1 + size + 1;
  }
  return blobs;
}

function git(...args: string[]): string {
  return execFileSync('git', args, { cwd: ROOT, encoding: 'utf8' });
}

/** Failures (a count above its line, or no line) and lowerings (a count below it) against the conf. */
export function judge(
  found: Map<string, number>,
  conf: Conf,
): { failures: string[]; lowered: string[] } {
  const failures: string[] = [];
  const lowered: string[] = [];
  for (const [rel, n] of found) {
    const allowed = conf.known.get(rel);
    if (allowed === undefined) {
      failures.push(
        `${rel}: ${n} desktop-width classes and no known line: a page does not add its own; use the layout's pieces (src/web/layout/AGENTS.md)`,
      );
    } else if (n > allowed) {
      failures.push(
        `${rel}: ${n} desktop-width classes, known ${allowed}: the count only shrinks`,
      );
    } else if (n < allowed) {
      lowered.push(
        `${rel}: ${n} desktop-width classes, known ${allowed}: lower it to ${n} in ${CONF} in this PR`,
      );
    }
  }
  for (const [rel, allowed] of conf.known) {
    if (!found.has(rel)) {
      lowered.push(
        `${rel}: none left, known ${allowed}: delete its known line in ${CONF} in this PR`,
      );
    }
  }
  return { failures, lowered };
}

async function main(): Promise<number> {
  const staged = process.argv.includes('--staged');
  const conf = readConf(
    staged
      ? readIndex([CONF]).get(CONF)!
      : readFileSync(join(ROOT, CONF), 'utf8'),
  );
  const listed = staged
    ? git('ls-files', '-z', '--', conf.src).split('\0')
    : walk(join(ROOT, conf.src));
  const paths = listed.filter((p) => p && isCounted(p, conf.exempt)).sort();
  const contents = staged
    ? readIndex(paths)
    : new Map(paths.map((p) => [p, readFileSync(join(ROOT, p), 'utf8')]));

  const isDesktop = await desktopClassifier();
  const scanner = new Scanner({});
  const found = new Map<string, number>();
  for (const rel of paths) {
    const n = countFile(scanner, isDesktop, rel, contents.get(rel)!);
    if (n > 0) found.set(rel, n);
  }

  const { failures, lowered } = judge(found, conf);
  const total = [...found.values()].reduce((a, b) => a + b, 0);
  const knownTotal = [...conf.known.values()].reduce((a, b) => a + b, 0);
  console.log(
    `lg-check files=${found.size} total=${total} known=${knownTotal}`,
  );
  for (const line of [...failures, ...lowered])
    console.error(`lg-check: ${line}`);
  return failures.length > 0 || lowered.length > 0 ? 1 : 0;
}

if (require.main === module) {
  main().then(
    (code) => process.exit(code),
    (err: unknown) => {
      console.error(err);
      process.exit(1);
    },
  );
}
